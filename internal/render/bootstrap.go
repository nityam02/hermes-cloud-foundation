package render

import (
	"fmt"
	"path/filepath"

	"github.com/nityam02/hermes-cloud-foundation/internal/config"
	"github.com/nityam02/hermes-cloud-foundation/internal/providers"
	"github.com/nityam02/hermes-cloud-foundation/internal/state"
)

// BootstrapEnvironment is the pseudo-environment name used for the state-backend
// bootstrap root (build dir, saved plans and history): _bootstrap-<provider>.
func BootstrapEnvironment(provider string) string { return "_bootstrap-" + provider }

// RenderBootstrap renders a root module for infra/bootstrap/<provider>/state-backend.
// It always uses the local backend (the remote backend does not exist yet: the
// chicken-and-egg problem); its state file is kept under
// <HermesDir>/state/_bootstrap/<project>/<provider>/terraform.tfstate and can be
// migrated into the new bucket afterwards (docs/operations/state-management.md).
func RenderBootstrap(p *config.Platform, opts Options) (*Result, error) {
	res, err := BuildBootstrap(p, opts)
	if err != nil {
		return nil, err
	}
	if err := writeFiles(res.Dir, res.Files); err != nil {
		return nil, err
	}
	return res, nil
}

// BuildBootstrap is RenderBootstrap without writing files.
func BuildBootstrap(p *config.Platform, opts Options) (*Result, error) {
	o, err := opts.withDefaults()
	if err != nil {
		return nil, err
	}
	a, ok := providers.Get(p.Cloud.Provider)
	if !ok {
		return nil, fmt.Errorf("render: unknown provider %q", p.Cloud.Provider)
	}
	if p.State.Bucket == "" {
		return nil, fmt.Errorf("render: set state.bucket to the bucket name the bootstrap should create")
	}
	modulesDir, modulesDigest, err := o.modules()
	if err != nil {
		return nil, err
	}
	source, err := moduleSource(o.OutDir, filepath.Join(modulesDir, "bootstrap", a.Name(), "state-backend"))
	if err != nil {
		return nil, err
	}
	statePath, err := filepath.Rel(o.OutDir, filepath.Join(o.HermesDir, "state", "_bootstrap", p.Project.Name, a.Name(), state.StateFile))
	if err != nil {
		return nil, fmt.Errorf("render: %w", err)
	}
	backend := state.Backend{Type: config.BackendLocal, Config: map[string]any{"path": filepath.ToSlash(statePath)}}

	providerBlocks := map[string]any{}
	for name, cfg := range a.ProviderConfigs(p) {
		if name == providers.PinGoogleBeta.LocalName {
			continue // the bootstrap module does not need google-beta
		}
		providerBlocks[name] = escapeTemplates(toGeneric(cfg))
	}
	var pins []providers.TerraformProvider
	for _, pin := range append(a.Providers(), providers.SharedProviders()...) {
		if pin.LocalName != providers.PinGoogleBeta.LocalName {
			pins = append(pins, pin)
		}
	}
	module := escapeTemplates(toGeneric(map[string]any{
		"project":     p.Project.Name,
		"region":      p.State.Region,
		"bucket_name": p.State.Bucket,
		"labels":      providers.Labels(p),
	})).(map[string]any)
	module["source"] = source

	root := map[string]any{
		"//": fmt.Sprintf("Generated by hermes state bootstrap (provider %s). Local state by design: the remote backend does not exist yet.", a.Name()),
		"terraform": map[string]any{
			"required_version":   requiredVersion(o.Engine),
			"required_providers": requiredProviders(pins),
			"backend":            map[string]any{backend.Type: backend.Config},
		},
		"provider": providerBlocks,
		"module":   map[string]any{"state_backend": module},
		"output": map[string]any{
			"bucket":         output("module.state_backend.bucket", "State bucket name."),
			"backend_config": output("module.state_backend.backend_config", "Backend settings for hermes.yaml state:/extensions."),
		},
	}
	data, err := encode(root)
	if err != nil {
		return nil, fmt.Errorf("render: encode: %w", err)
	}
	files := map[string][]byte{RootFile: data}
	return &Result{
		Dir: o.OutDir, RootFile: filepath.Join(o.OutDir, RootFile), Digest: digestFiles(files),
		ModulesDigest: modulesDigest, ModulesDir: modulesDir, Provider: a.Name(), Engine: o.Engine,
		Backend: backend, Files: files,
	}, nil
}
