// Package render turns a normalized Platform into an OpenTofu/Terraform root module in
// JSON syntax (.hermes/build/<env>/main.tf.json) that calls the provider composition
// module with the contract variables (infra/contract/variables.tf).
//
// Output is deterministic: maps are encoded with sorted keys, and the digest (sha256 of
// the rendered files) identifies exactly what a saved plan was made from.
package render

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/nityam02/hermes-cloud-foundation/infra"
	"github.com/nityam02/hermes-cloud-foundation/internal/config"
	"github.com/nityam02/hermes-cloud-foundation/internal/execution"
	"github.com/nityam02/hermes-cloud-foundation/internal/providers"
	"github.com/nityam02/hermes-cloud-foundation/internal/state"
)

// RootFile is the rendered root module file name.
const RootFile = "main.tf.json"

// Options control rendering.
type Options struct {
	// OutDir is the root module directory, conventionally .hermes/build/<env>.
	OutDir string
	// ModulesDir is the directory holding contract/, modules/, providers/ and bootstrap/.
	// "" extracts the embedded modules to <HermesDir>/modules/<Version>.
	ModulesDir string
	// Engine is tofu or terraform ("" = tofu). OpenTofu-only features (client-side state
	// encryption) are rendered only for tofu.
	Engine string
	// EngineVersion is the detected engine version (zero when unknown); used for the
	// engine floor check.
	EngineVersion execution.Version
	// LocalBackend forces the local backend (offline validation and tests only; never
	// used by `hermes plan`).
	LocalBackend bool

	// HermesDir is the .hermes directory ("" = two levels above OutDir).
	HermesDir string
	// Version is the CLI version, used for the modules directory name ("" = "dev").
	Version string
	// ReplaceModules allows replacing an extracted modules directory whose content differs
	// from the embedded modules.
	ReplaceModules bool
	// ModulesFS overrides the embedded module tree (tests).
	ModulesFS fs.FS
}

// Result describes a rendered root module.
type Result struct {
	Dir           string        `json:"dir"`
	RootFile      string        `json:"root_file"`
	Digest        string        `json:"digest"`         // sha256 of the rendered files
	ModulesDigest string        `json:"modules_digest"` // sha256 of the module tree used
	ModulesDir    string        `json:"modules_dir"`
	Provider      string        `json:"provider"`
	Engine        string        `json:"engine"`
	Backend       state.Backend `json:"backend"`
	// Files maps file name to content (what was written to Dir).
	Files map[string][]byte `json:"-"`
}

// Render writes the root module for p and returns its description.
func Render(p *config.Platform, opts Options) (*Result, error) {
	res, err := Build(p, opts)
	if err != nil {
		return nil, err
	}
	if err := writeFiles(res.Dir, res.Files); err != nil {
		return nil, err
	}
	return res, nil
}

// Build computes the root module without writing it (the modules directory is still
// extracted when needed, because the module source path and digest depend on it). Apply
// uses Build to detect a stale saved plan.
func Build(p *config.Platform, opts Options) (*Result, error) {
	o, err := opts.withDefaults()
	if err != nil {
		return nil, err
	}
	a, ok := providers.Get(p.Cloud.Provider)
	if !ok {
		return nil, fmt.Errorf("render: unknown provider %q", p.Cloud.Provider)
	}
	modulesDir, modulesDigest, err := o.modules()
	if err != nil {
		return nil, err
	}
	source, err := moduleSource(o.OutDir, filepath.Join(modulesDir, "providers", a.Name(), "platform"))
	if err != nil {
		return nil, err
	}
	localState, err := filepath.Rel(o.OutDir, filepath.Join(o.HermesDir, "state", filepath.FromSlash(state.Dir(p)), state.StateFile))
	if err != nil {
		return nil, fmt.Errorf("render: %w", err)
	}
	backend, err := state.ForPlatform(p, filepath.ToSlash(localState), o.LocalBackend)
	if err != nil {
		return nil, fmt.Errorf("render: %w", err)
	}
	enc, err := state.Encryption(p, o.Engine == execution.BinaryOpenTofu)
	if err != nil {
		return nil, fmt.Errorf("render: %w", err)
	}

	tf := map[string]any{
		"required_version":   requiredVersion(o.Engine),
		"required_providers": requiredProviders(append(a.Providers(), providers.SharedProviders()...)),
		"backend":            map[string]any{backend.Type: backend.Config},
	}
	if enc != nil {
		tf["encryption"] = enc
	}
	providerBlocks := map[string]any{}
	for name, cfg := range a.ProviderConfigs(p) {
		providerBlocks[name] = escapeTemplates(toGeneric(cfg))
	}
	module := moduleArgs(p, a.Name())
	module["source"] = source

	root := map[string]any{
		"//":        fmt.Sprintf("Generated by hermes from %s (environment %s, provider %s). Do not edit: change the spec and run `hermes render`.", filepath.Base(sourceName(p)), p.Environment, a.Name()),
		"terraform": tf,
		"provider":  providerBlocks,
		"module":    map[string]any{"platform": module},
		"output": map[string]any{
			"bindings":            output("module.platform.bindings", "Non-secret connection metadata (infra/contract/outputs.md)."),
			"service_environment": output("module.platform.service_environment", "Non-secret environment variables injected into each service."),
			"secret_environment":  output("module.platform.secret_environment", "Secret references (never values) injected into each service."),
		},
	}
	data, err := encode(root)
	if err != nil {
		return nil, fmt.Errorf("render: encode: %w", err)
	}
	files := map[string][]byte{RootFile: data}
	return &Result{
		Dir:           o.OutDir,
		RootFile:      filepath.Join(o.OutDir, RootFile),
		Digest:        digestFiles(files),
		ModulesDigest: modulesDigest,
		ModulesDir:    modulesDir,
		Provider:      a.Name(),
		Engine:        o.Engine,
		Backend:       backend,
		Files:         files,
	}, nil
}

func sourceName(p *config.Platform) string {
	if p.Source == "" {
		return "hermes.yaml"
	}
	return p.Source
}

func (o Options) withDefaults() (Options, error) {
	if o.OutDir == "" {
		return o, fmt.Errorf("render: OutDir is required")
	}
	var err error
	if o.OutDir, err = realPath(o.OutDir); err != nil {
		return o, fmt.Errorf("render: %w", err)
	}
	if o.HermesDir == "" {
		o.HermesDir = filepath.Dir(filepath.Dir(o.OutDir))
	}
	if o.HermesDir, err = realPath(o.HermesDir); err != nil {
		return o, fmt.Errorf("render: %w", err)
	}
	if o.Version == "" {
		o.Version = "dev"
	}
	switch o.Engine {
	case "":
		o.Engine = execution.BinaryOpenTofu
	case execution.BinaryOpenTofu, execution.BinaryTerraform:
	default:
		return o, fmt.Errorf("render: unknown engine %q", o.Engine)
	}
	if o.EngineVersion != (execution.Version{}) {
		floor := execution.MinOpenTofu
		if o.Engine == execution.BinaryTerraform {
			floor = execution.MinTerraform
		}
		if o.EngineVersion.Less(floor) {
			return o, fmt.Errorf("render: %s %s is older than the supported minimum %s", o.Engine, o.EngineVersion, floor)
		}
	}
	return o, nil
}

func (o Options) modules() (dir, digest string, err error) {
	if o.ModulesDir != "" {
		dir, err = realPath(o.ModulesDir)
		if err != nil {
			return "", "", fmt.Errorf("render: %w", err)
		}
		digest, err = DigestFS(os.DirFS(dir))
		if err != nil {
			return "", "", fmt.Errorf("render: digest %s: %w", dir, err)
		}
		return dir, digest, nil
	}
	src := o.ModulesFS
	if src == nil {
		src = infra.FS
	}
	dir = filepath.Join(o.HermesDir, "modules", safeName(o.Version))
	digest, err = ExtractModules(src, dir, o.Version, o.ReplaceModules)
	return dir, digest, err
}

// realPath returns the absolute path with symlinks resolved in its longest existing
// prefix. Relative module sources must be computed between real paths: the engine resolves
// them from the real directory (e.g. macOS /var -> /private/var).
func realPath(p string) (string, error) {
	abs, err := filepath.Abs(p)
	if err != nil {
		return "", err
	}
	rest := ""
	for cur := abs; ; {
		if r, err := filepath.EvalSymlinks(cur); err == nil {
			return filepath.Join(r, rest), nil
		}
		parent := filepath.Dir(cur)
		if parent == cur {
			return abs, nil
		}
		rest = filepath.Join(filepath.Base(cur), rest)
		cur = parent
	}
}

func safeName(v string) string {
	return strings.Map(func(r rune) rune {
		if r == '/' || r == '\\' || r == ' ' || r == ':' {
			return '_'
		}
		return r
	}, v)
}

// moduleSource returns the local module path relative to the root directory, which the
// engine requires to start with ./ or ../ .
func moduleSource(rootDir, moduleDir string) (string, error) {
	rel, err := filepath.Rel(rootDir, moduleDir)
	if err != nil {
		return "", fmt.Errorf("render: module path: %w", err)
	}
	rel = filepath.ToSlash(rel)
	if !strings.HasPrefix(rel, "../") && !strings.HasPrefix(rel, "./") {
		rel = "./" + rel
	}
	return rel, nil
}

func requiredVersion(engine string) string {
	if engine == execution.BinaryTerraform {
		return ">= " + execution.MinTerraform.String()
	}
	return ">= " + execution.MinOpenTofu.String()
}

func requiredProviders(ps []providers.TerraformProvider) map[string]any {
	out := map[string]any{}
	for _, p := range ps {
		out[p.LocalName] = map[string]any{"source": p.Source, "version": p.Version}
	}
	return out
}

func output(expr, desc string) map[string]any {
	return map[string]any{"value": "${" + expr + "}", "description": desc}
}

// moduleArgs maps the normalized spec onto the contract variables.
func moduleArgs(p *config.Platform, provider string) map[string]any {
	w := p.Workloads
	args := map[string]any{
		"project":       p.Project.Name,
		"environment":   p.Environment,
		"region":        p.Cloud.Region,
		"protected":     p.Protected,
		"labels":        providers.Labels(p),
		"network":       p.Network,
		"security":      p.Security,
		"compute":       w.Compute,
		"database":      w.Database,
		"storage":       w.Storage,
		"messaging":     w.Messaging,
		"secrets":       w.Secrets,
		"observability": w.Observability,
		"extensions":    p.Extensions.For(provider),
	}
	return escapeTemplates(toGeneric(args)).(map[string]any)
}

// toGeneric converts structs to JSON-compatible maps (spec field names via json tags).
func toGeneric(v any) any {
	data, err := json.Marshal(v)
	if err != nil {
		panic(fmt.Sprintf("render: marshal %T: %v", v, err)) // spec types always marshal
	}
	var out any
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	if err := dec.Decode(&out); err != nil {
		panic(fmt.Sprintf("render: unmarshal %T: %v", v, err))
	}
	return out
}

// escapeTemplates escapes "${" and "%{" in every string value. In the JSON syntax,
// strings in expression positions are templates; user-provided values (env values,
// commands, labels) must never be evaluated as expressions.
func escapeTemplates(v any) any {
	switch t := v.(type) {
	case string:
		t = strings.ReplaceAll(t, "${", "$${")
		return strings.ReplaceAll(t, "%{", "%%{")
	case map[string]any:
		for k, x := range t {
			t[k] = escapeTemplates(x)
		}
		return t
	case []any:
		for i, x := range t {
			t[i] = escapeTemplates(x)
		}
		return t
	}
	return v
}

func encode(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func digestFiles(files map[string][]byte) string {
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	h := sha256.New()
	for _, n := range names {
		fmt.Fprintf(h, "%s\x00%d\x00", n, len(files[n]))
		h.Write(files[n])
	}
	return hex.EncodeToString(h.Sum(nil))
}

func writeFiles(dir string, files map[string][]byte) error {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("render: %w", err)
	}
	for name, data := range files {
		tmp := filepath.Join(dir, "."+name+".tmp")
		if err := os.WriteFile(tmp, data, 0o600); err != nil {
			return fmt.Errorf("render: %w", err)
		}
		if err := os.Rename(tmp, filepath.Join(dir, name)); err != nil {
			return fmt.Errorf("render: %w", err)
		}
	}
	return nil
}
