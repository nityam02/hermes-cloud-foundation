// AWSRequest describes the AWS side of a migration.
type AWSRequest struct {
	Profile    string `json:"profile"`     // the operator's own sign-in (shared config profile); "" = default chain
	Region     string `json:"region"`      // home region for STS and the quick read test
	RoleARN    string `json:"role_arn"`    // the customer's read-only discovery role
	ExternalID string `json:"external_id"` // generated by Hermes, required by the role's trust policy
}

// AWSDeps are the AWS calls, replaceable in tests so no check needs a real account.
type AWSDeps struct {
	// Identity returns the caller ARN and account for the operator's own sign-in.
	Identity func(ctx context.Context, profile, region string) (arn, account string, err error)
	// Probe assumes the role and reads one region through the read-only guard.
	Probe func(ctx context.Context, req AWSRequest) (*inventory.Inventory, error)
}

var (
	roleARNPattern = regexp.MustCompile(`^arn:aws[a-zA-Z-]*:iam::[0-9]{12}:role/[\w+=,.@/-]+$`)
	externalIDMin  = 16
)

// ValidateAWSRequest checks the role ARN and external ID without calling AWS.
func ValidateAWSRequest(req AWSRequest) error {
	if !roleARNPattern.MatchString(req.RoleARN) {
		return fmt.Errorf("the role ARN should look like arn:aws:iam::123456789012:role/HermesDiscoveryReadOnly")
	}
	if len(req.ExternalID) < externalIDMin {
		return fmt.Errorf("the external ID must be at least %d characters", externalIDMin)
	}
	return nil
}

// IsRootARN reports whether an ARN is an account root user.
func IsRootARN(arn string) bool { return strings.HasSuffix(arn, ":root") }

// CheckAWS runs the AWS connection test: inputs, who the operator is, whether the role can be assumed,
// and whether it can read the services Hermes inspects.
func CheckAWS(ctx context.Context, d AWSDeps, req AWSRequest) Result {
	var r Result
	if req.Region == "" {
		req.Region = "us-east-1"
	}
	later := [][2]string{{"role", "Assume the read-only role"}, {"read", "Read the account"}, {"access", "Check read access"}}

	// 1. Inputs
	if !roleARNPattern.MatchString(req.RoleARN) {
		r.Steps = append(r.Steps, Step{ID: "inputs", Title: "Role details look right", Status: Fail,
			Detail: "The role ARN should look like arn:aws:iam::123456789012:role/HermesDiscoveryReadOnly.",
			Fix:    "Copy the RoleArn output from the CloudFormation stack that created the role."})
		skipRest(&r, append([][2]string{{"identity", "Find who you are signed in as"}}, later...), "Fix the role details first.")
		finish(&r, "", "The role details need fixing.")
		return r
	}
	if len(req.ExternalID) < externalIDMin {
		r.Steps = append(r.Steps, Step{ID: "inputs", Title: "Role details look right", Status: Fail,
			Detail: fmt.Sprintf("The external ID must be at least %d characters.", externalIDMin),
			Fix:    "Use the external ID Hermes generated for you in the previous step."})
		skipRest(&r, append([][2]string{{"identity", "Find who you are signed in as"}}, later...), "Fix the role details first.")
		finish(&r, "", "The role details need fixing.")
		return r
	}
	r.Steps = append(r.Steps, Step{ID: "inputs", Title: "Role details look right", Status: Pass, Detail: req.RoleARN})

	// 2. Operator identity
	cctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	arn, account, err := d.Identity(cctx, req.Profile, req.Region)
	cancel()
	if err != nil {
		title, fix := classifyAWS(err, req, "")
		r.Steps = append(r.Steps, Step{ID: "identity", Title: "Find who you are signed in as", Status: Fail, Detail: title, Fix: fix})
		skipRest(&r, later, "Sign in first.")
		finish(&r, "", "Hermes could not find your AWS sign-in.")
		return r
	}
	r.Identity = arn
	if IsRootARN(arn) {
		r.Steps = append(r.Steps, Step{ID: "identity", Title: "Find who you are signed in as", Status: Fail,
			Detail: fmt.Sprintf("You are signed in as the root user of account %s. AWS never lets the root user assume a role.", account),
			Fix:    "Sign in as an IAM user, an IAM role or an SSO identity instead (for example `aws login --profile hermes` after signing in to the console as that user), then pick that profile."})
		skipRest(&r, later, "Sign in as a non-root identity first.")
		finish(&r, "", "You are signed in as root, which cannot assume roles.")
		return r
	}
	r.Steps = append(r.Steps, Step{ID: "identity", Title: "Find who you are signed in as", Status: Pass, Detail: fmt.Sprintf("%s (account %s)", arn, account)})

	// 3. Assume the role and read one region
	pctx, cancel := context.WithTimeout(ctx, 120*time.Second)
	inv, err := d.Probe(pctx, req)
	cancel()
	if err != nil {
		title, fix := classifyAWS(err, req, arn)
		r.Steps = append(r.Steps, Step{ID: "role", Title: "Assume the read-only role", Status: Fail, Detail: title, Fix: fix})
		skipRest(&r, later[1:], "The role must be assumed first.")
		finish(&r, "", "Hermes could not use the role.")
		return r
	}
	r.Steps = append(r.Steps, Step{ID: "role", Title: "Assume the read-only role", Status: Pass, Detail: "Assumed with the external ID. The session lasts one hour."})
	r.Steps = append(r.Steps, Step{ID: "read", Title: "Read the account", Status: Pass,
		Detail: fmt.Sprintf("Found %d resources in %s (%d relationships).", len(inv.Resources), req.Region, len(inv.Relationships))})

	// 4. Gaps
	if len(inv.Gaps) == 0 {
		r.Steps = append(r.Steps, Step{ID: "access", Title: "Check read access", Status: Pass, Detail: "The role can read every service Hermes inspects."})
	} else {
		r.Steps = append(r.Steps, Step{ID: "access", Title: "Check read access", Status: Warn,
			Detail: fmt.Sprintf("%d read calls were denied or unsupported: %s.", len(inv.Gaps), summarizeGaps(inv.Gaps)),
			Fix:    "Discovery still works, but anything behind those calls will be missing from the plan. Update the role with the latest template to add the permissions."})
	}
	finish(&r, "Connected. Hermes can read this account through the role.", "Hermes could not use the role.")
	return r
}

func summarizeGaps(gaps []inventory.Gap) string {
	seen := map[string]bool{}
	var out []string
	for _, g := range gaps {
		k := g.Service + ":" + g.Operation
		if !seen[k] {
			seen[k] = true
			out = append(out, k)
		}
	}
	sort.Strings(out)
	if len(out) > 5 {
		out = append(out[:5], fmt.Sprintf("and %d more", len(out)-5))
	}
	return strings.Join(out, ", ")
}

// ExplainAWSError turns an error from the operator's own sign-in into a plain sentence and a fix.
func ExplainAWSError(err error, profile string) (detail, fix string) {
	return classifyAWS(err, AWSRequest{Profile: profile}, "")
}

// classifyAWS turns an AWS error into a plain sentence and a fix.
func classifyAWS(err error, req AWSRequest, callerARN string) (detail, fix string) {
	msg := err.Error()
	switch {
	case strings.Contains(msg, "Roles may not be assumed by root"):
		return "AWS refused: the root user cannot assume roles.", "Sign in as an IAM user, role or SSO identity."
	case strings.Contains(msg, "InvalidClientTokenId") || strings.Contains(msg, "ExpiredToken") || strings.Contains(msg, "failed to refresh cached credentials, no EC2 IMDS") || strings.Contains(msg, "Unable to load a existing login session") || strings.Contains(msg, "load login token") || strings.Contains(msg, "failed to refresh cached credentials"):
		p := req.Profile
		if p == "" {
			p = "default"
		}
		return fmt.Sprintf("The profile %s is not signed in, or its sign-in has expired.", p),
			"Choose Sign in to AWS on this page (it runs `aws login` for you), or pick a profile that is signed in."
	case strings.Contains(msg, "AssumeRole") && (strings.Contains(msg, "AccessDenied") || strings.Contains(msg, "not authorized")):
		who := "your sign-in"
		if callerARN != "" {
			who = callerARN
		}
		return "AWS refused to let you assume the role.",
			fmt.Sprintf("Check three things: the role's trust policy names %s, the external ID matches the one used to create the role, and your sign-in is allowed to call sts:AssumeRole on the role.", who)
	case strings.Contains(msg, "NoCredentialProviders") || strings.Contains(msg, "no valid providers in chain"):
		return "No AWS sign-in was found for this profile.", "Choose Sign in to AWS on this page, or pick a profile that is signed in."
	case strings.Contains(msg, "context deadline exceeded"):
		return "AWS did not answer in time.", "Check your network and try again."
	}
	return truncate(msg, 300), "Check the message above. If it names a permission, add it to the sign-in or the role."
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}

// DefaultAWSDeps are the real AWS calls: STS for identity and the guarded read-only discovery client.
func DefaultAWSDeps() AWSDeps {
	return AWSDeps{
		Identity: func(ctx context.Context, profile, region string) (string, string, error) {
			cfg, err := awsinv.NewSession(ctx, awsinv.SessionOptions{Profile: profile, Region: region})
			if err != nil {
				return "", "", err
			}
			out, err := awsinv.NewClientFactory(cfg)(region).STS.GetCallerIdentity(ctx, nil)
			if err != nil {
				return "", "", err
			}
			return deref(out.Arn), deref(out.Account), nil
		},
		Probe: func(ctx context.Context, req AWSRequest) (*inventory.Inventory, error) {
			return DiscoverAWS(ctx, req, []string{req.Region})
		},
	}
}

func deref(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}

// DiscoverAWS assumes the read-only role and discovers the given regions through the guarded client.
func DiscoverAWS(ctx context.Context, req AWSRequest, regions []string) (*inventory.Inventory, error) {
	home := req.Region
	if home == "" {
		home = "us-east-1"
	}
	cfg, err := awsinv.NewSession(ctx, awsinv.SessionOptions{Profile: req.Profile, Region: home, RoleARN: req.RoleARN, ExternalID: req.ExternalID})
	if err != nil {
		return nil, err
	}
	d := &awsinv.Discoverer{
		Clients: awsinv.NewClientFactory(cfg),
		Options: awsinv.Options{HomeRegion: home, Regions: regions, RoleARN: req.RoleARN, ExternalIDUsed: true, Generator: "hermes-ui"},
	}
	return d.Run(ctx)
}

// AWSProfile is a profile in the shared AWS config files and how it gets credentials.
type AWSProfile struct {
	Name string `json:"name"`
	// Kind is login (console sign-in, `aws login`), sso (IAM Identity Center, `aws sso login`), keys
	// (access keys saved in a file), role (assumes a role from another profile), process (an external
	// credential helper) or other.
	Kind string `json:"kind"`
}

// AWSProfiles lists the profiles in the shared AWS config and credentials files. Only section names
// and key names are read: no value, and so no credential, is ever kept or returned.
func AWSProfiles() []AWSProfile {
	home, _ := os.UserHomeDir()
	files := []string{os.Getenv("AWS_CONFIG_FILE"), os.Getenv("AWS_SHARED_CREDENTIALS_FILE")}
	if files[0] == "" {
		files[0] = filepath.Join(home, ".aws", "config")
	}
	if files[1] == "" {
		files[1] = filepath.Join(home, ".aws", "credentials")
	}
	keys := map[string]map[string]bool{}
	var order []string
	for _, f := range files {
		data, err := os.ReadFile(f) //nolint:gosec // the standard AWS_CONFIG_FILE / ~/.aws paths on the operator's own machine; only names are used
		if err != nil {
			continue
		}
		current := ""
		for _, line := range strings.Split(string(data), "\n") {
			line = strings.TrimSpace(line)
			if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, ";") {
				continue
			}
			if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
				name := strings.TrimSpace(strings.TrimSuffix(strings.TrimPrefix(line, "["), "]"))
				name = strings.TrimSpace(strings.TrimPrefix(name, "profile "))
				current = ""
				if name == "" || strings.HasPrefix(name, "sso-session") || strings.HasPrefix(name, "services ") {
					continue
				}
				current = name
				if keys[name] == nil {
					keys[name] = map[string]bool{}
					order = append(order, name)
				}
				continue
			}
			if k, _, ok := strings.Cut(line, "="); ok && current != "" {
				keys[current][strings.ToLower(strings.TrimSpace(k))] = true
			}
		}
	}
	sort.Strings(order)
	out := make([]AWSProfile, 0, len(order))
	for _, n := range order {
		out = append(out, AWSProfile{Name: n, Kind: profileKind(keys[n])})
	}
	return out
}

func profileKind(k map[string]bool) string {
	switch {
	case k["role_arn"]:
		return "role"
	case k["sso_session"] || k["sso_start_url"]:
		return "sso"
	case k["login_session"]:
		return "login"
	case k["credential_process"]:
		return "process"
	case k["aws_access_key_id"]:
		return "keys"
	}
	return "other"
}
