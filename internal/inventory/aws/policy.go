// APIGatewayReadResources scopes apigateway:GET to the HTTP/WebSocket API collection.
var APIGatewayReadResources = []string{"arn:aws:apigateway:*::/apis", "arn:aws:apigateway:*::/apis/*"}

// ImpliedIAMActions are permissions that AWS checks in addition to the action of the API that
// Hermes calls. They are not operations Hermes calls itself. Found in a real account run:
// cloudformation:DescribeStacks without a stack name also requires cloudformation:ListStacks
// (the first run recorded access-denied gaps until it was added).
var ImpliedIAMActions = []string{"cloudformation:ListStacks"}

// DiscoveryPolicy generates the least-privilege read-only IAM policy from the operation
// registry. List/Describe actions do not support resource-level scoping, so "*" is used for
// them; API Gateway reads are scoped to /apis.
func DiscoveryPolicy() PolicyDocument {
	set := map[string]bool{}
	apigw := map[string]bool{}
	for _, op := range Registry() {
		if op.IAMAction == "" {
			continue
		}
		if op.Service == SvcAPIGatewayV2 {
			apigw[op.IAMAction] = true
			continue
		}
		set[op.IAMAction] = true
	}
	for _, a := range ImpliedIAMActions {
		set[a] = true
	}
	doc := PolicyDocument{Version: "2012-10-17"}
	doc.Statement = append(doc.Statement, PolicyStatement{Sid: "HermesReadOnlyDiscovery", Effect: "Allow", Action: sortedKeys(set), Resource: "*"})
	if len(apigw) > 0 {
		doc.Statement = append(doc.Statement, PolicyStatement{Sid: "HermesReadOnlyApiGateway", Effect: "Allow", Action: sortedKeys(apigw), Resource: APIGatewayReadResources})
	}
	deny := append([]string(nil), DeniedIAMActions...)
	sort.Strings(deny)
	doc.Statement = append(doc.Statement, PolicyStatement{Sid: "HermesDenySecretAndDataReads", Effect: "Deny", Action: deny, Resource: "*"})
	return doc
}

// DiscoveryPolicyJSON renders DiscoveryPolicy as indented JSON with a trailing newline. This
// is the exact content of migration/discovery/aws-readonly-discovery-policy.json.
func DiscoveryPolicyJSON() []byte {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	_ = enc.Encode(DiscoveryPolicy())
	return buf.Bytes()
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// DiscoveryRoleTemplate returns the CloudFormation template (JSON) that creates the
// HermesDiscoveryReadOnly role: trust to one principal with an sts:ExternalId condition,
// 1-hour maximum session, and the generated read-only policy inline. It is the exact content
// of migration/discovery/cloudformation/hermes-discovery-role.json (a test asserts it).
func DiscoveryRoleTemplate() []byte {
	tpl := map[string]any{
		"AWSTemplateFormatVersion": "2010-09-09",
		"Description":              "Hermes read-only discovery role (HermesDiscoveryReadOnly): Describe/List/Get metadata only, explicit deny for secret and data reads, ExternalId required, 1-hour sessions. Generated by Hermes; do not edit.",
		"Parameters": map[string]any{
			"TrustedPrincipalArn": map[string]any{"Type": "String",
				"Description":    "ARN of the principal that runs hermes inventory (an IAM role or user in the operator account, or arn:aws:iam::<account>:root).",
				"AllowedPattern": `^arn:aws[a-zA-Z-]*:iam::[0-9]{12}:(root|role/.+|user/.+)$`},
			"ExternalId": map[string]any{"Type": "String", "MinLength": 16, "MaxLength": 1224,
				"AllowedPattern": `^[\w+=,.@:/-]+$`,
				"Description":    "Random value shared out-of-band with the operator; required as sts:ExternalId (prevents confused-deputy use of the role)."},
			"RoleName": map[string]any{"Type": "String", "Default": "HermesDiscoveryReadOnly"},
		},
		"Resources": map[string]any{
			"DiscoveryRole": map[string]any{
				"Type": "AWS::IAM::Role",
				"Properties": map[string]any{
					"RoleName":           map[string]any{"Ref": "RoleName"},
					"Description":        "Hermes read-only discovery (agentless, no secret values, no data reads)",
					"MaxSessionDuration": 3600,
					"AssumeRolePolicyDocument": map[string]any{
						"Version": "2012-10-17",
						"Statement": []any{map[string]any{
							"Effect":    "Allow",
							"Principal": map[string]any{"AWS": map[string]any{"Ref": "TrustedPrincipalArn"}},
							"Action":    "sts:AssumeRole",
							"Condition": map[string]any{"StringEquals": map[string]any{"sts:ExternalId": map[string]any{"Ref": "ExternalId"}}},
						}},
					},
					"Policies": []any{map[string]any{"PolicyName": "HermesReadOnlyDiscovery", "PolicyDocument": DiscoveryPolicy()}},
					"Tags":     []any{map[string]any{"Key": "hermes-component", "Value": "discovery"}, map[string]any{"Key": "hermes-managed-by", "Value": "hermes"}},
				},
			},
		},
		"Outputs": map[string]any{
			"RoleArn": map[string]any{"Description": "Pass to hermes inventory aws --role-arn", "Value": map[string]any{"Fn::GetAtt": []any{"DiscoveryRole", "Arn"}}},
		},
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	_ = enc.Encode(tpl)
	return buf.Bytes()
}
